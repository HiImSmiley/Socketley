# Show main menu
main_menu() {
    show_header
    echo -e "${BOLD}What would you like to learn about?${NC}\n"
    echo -e "  ${GREEN}1)${NC} Quick Start Guide"
    echo -e "  ${GREEN}2)${NC} CLI Commands"
    echo -e "  ${GREEN}3)${NC} Runtime Types"
    echo -e "  ${GREEN}4)${NC} Flags & Options"
    echo -e "  ${GREEN}5)${NC} Lua Configuration"
    echo -e "  ${GREEN}6)${NC} Examples"
    echo -e "  ${GREEN}7)${NC} Architecture Overview"
    echo -e "  ${GREEN}8)${NC} Troubleshooting"
    echo -e "  ${GREEN}9)${NC} Installation & Packaging"
    echo -e "  ${GREEN}10)${NC} C++ SDK"
    echo ""
    echo -e "  ${RED}q)${NC} Quit"
    echo ""
    read -p "Enter choice: " choice
    case $choice in
        1) quick_start ;;
        2) cli_commands ;;
        3) runtime_types ;;
        4) flags_options ;;
        5) lua_config ;;
        6) examples_menu ;;
        7) architecture ;;
        8) troubleshooting ;;
        9) installation_help ;;
        10) sdk_help ;;
        q|Q) exit 0 ;;
        *) main_menu ;;
    esac
}

# Quick Start Guide
quick_start() {
    show_header
    echo -e "${BOLD}${YELLOW}═══ Quick Start Guide ═══${NC}\n"

    echo -e "${BOLD}Step 1: Daemon${NC}"
    echo "  When installed via package, the daemon runs as a systemd service"
    echo "  automatically — no manual startup needed."
    echo -e "  Dev mode: ${CYAN}./bin/Release/socketley daemon &${NC}"
    echo ""

    echo -e "${BOLD}Step 2: Create a Server${NC}"
    echo -e "  ${CYAN}socketley create server myserver -p 9000 -s${NC}"
    echo "  Creates and starts a server on port 9000."
    echo ""

    echo -e "${BOLD}Step 3: Create a Client${NC}"
    echo -e "  ${CYAN}socketley create client myclient -t 127.0.0.1:9000 -s${NC}"
    echo "  Connects to the server."
    echo ""

    echo -e "${BOLD}Step 4: Check Status${NC}"
    echo -e "  ${CYAN}socketley ls${NC}      # All runtimes"
    echo -e "  ${CYAN}socketley ps${NC}      # Running only"
    echo -e "  ${CYAN}socketley ps -a${NC}   # Running, stopped and failed"
    echo ""

    echo -e "${BOLD}Step 5: Stop & Cleanup${NC}"
    echo -e "  ${CYAN}socketley stop myserver myclient${NC}"
    echo -e "  ${CYAN}socketley remove myserver myclient${NC}"
    echo ""

    read -p "Press Enter to continue..."
    main_menu
}

# CLI Commands
cli_commands() {
    show_header
    echo -e "${BOLD}${YELLOW}═══ CLI Commands ═══${NC}\n"

    echo -e "${BOLD}daemon [--sqpoll|--no-sqpoll] [--cpus <set>]${NC}"
    echo "  Start the daemon. When installed, runs as a systemd service"
    echo "  automatically. Only needed manually in dev mode."
    echo "  The flags shape the ring this daemon creates — the command-line"
    echo "  spelling of SOCKETLEY_SQPOLL / SOCKETLEY_CPUS, and they win when"
    echo "  both are given. Any other argument is refused rather than ignored."
    echo -e "  ${CYAN}sudo systemctl start socketley${NC}  # installed"
    echo -e "  ${CYAN}./bin/Release/socketley daemon &${NC}  # dev mode"
    echo -e "  ${CYAN}./bin/Release/socketley daemon --sqpoll --cpus 0-3 &${NC}"
    echo ""
    echo -e "${BOLD}daemon --name <name> [--cluster <dir>]${NC}"
    echo "  Configure the running daemon for cluster mode."
    echo "  --name sets the daemon identity, --cluster enables discovery."
    echo "  Name can be changed at any time (cluster file is republished);"
    echo "  a rename the cluster refuses leaves the old name in place."
    echo "  A node killed and restarted inside the 10s staleness window"
    echo "  reclaims its own entry — same host, same control socket, same"
    echo "  boot id means the writer is gone. A DIFFERENT daemon claiming a"
    echo "  live name is refused, named in the log, and reported by every"
    echo "  'socketley cluster' subcommand. Never accepted and ignored."
    echo -e "  ${CYAN}socketley daemon --name node1 --cluster /shared/cluster${NC}"
    echo -e "  ${CYAN}socketley daemon --name new-name${NC}  # rename"
    echo ""

    echo -e "${BOLD}create <type> <name> [flags]${NC}"
    echo "  Create a new runtime"
    echo -e "  ${CYAN}socketley create server api -p 9000 -s${NC}"
    echo ""

    echo -e "${BOLD}attach <type> <name> <port> [--owner <name>]${NC}"
    echo "  Register an external process as a runtime visible in ls/ps."
    echo "  The daemon does NOT bind the port or manage I/O — the external"
    echo "  process owns its connections. Useful for SDK-embedded runtimes."
    echo -e "  ${CYAN}socketley attach server my-app 8080${NC}"
    echo -e "  ${CYAN}socketley attach server my-app 8080 --owner api${NC}"
    echo ""

    echo -e "${BOLD}add <path> [--name <name>] [-s]${NC}"
    echo "  Register and manage an external binary (C++ SDK). The daemon"
    echo "  fork+exec's the binary and manages its full lifecycle:"
    echo "  auto-restart on crash, re-launch on daemon boot."
    echo -e "  ${CYAN}socketley add /usr/local/bin/myapp -s${NC}"
    echo -e "  ${CYAN}socketley add /usr/local/bin/myapp --name chat${NC}"
    echo ""

    echo -e "${BOLD}start <name|pattern>... [-i]${NC}"
    echo "  Start runtimes. Accepts multiple names, glob patterns (*,?,[])"
    echo "  -i: Interactive mode (stdin/stdout live session, single name only)"
    echo "      Refused for a proxy: it relays between a client and a backend and"
    echo "      has no stream of its own. Nothing is started when it is refused."
    echo -e "  ${CYAN}socketley start api${NC}"
    echo -e "  ${CYAN}socketley start api -i${NC}    # interactive session"
    echo -e "  ${CYAN}socketley start *${NC}         # start all non-running"
    echo -e "  ${CYAN}socketley start my*${NC}       # start all starting with 'my'"
    echo "  A runtime in a worker process is waited for: the port is accepting by"
    echo "    the time the command returns, and exit 1 names the runtime if the"
    echo "    worker refused its configuration or its on_start raised.  One 2s"
    echo "    budget for the whole command, not one per runtime."
    echo ""

    echo -e "${BOLD}stop <name|pattern>...${NC}"
    echo "  Stop running runtimes. Accepts multiple names, glob patterns"
    echo -e "  ${CYAN}socketley stop api${NC}"
    echo -e "  ${CYAN}socketley stop api cli${NC}  # stop both"
    echo -e "  ${CYAN}socketley stop my*${NC}      # stop all starting with 'my'"
    echo -e "  ${CYAN}socketley stop *${NC}        # stop all running"
    echo ""

    echo -e "${BOLD}remove <name|pattern>...${NC}"
    echo "  Remove runtimes. Accepts multiple names, glob patterns"
    echo -e "  ${CYAN}socketley remove api${NC}"
    echo -e "  ${CYAN}socketley remove api cli${NC}  # remove both"
    echo -e "  ${CYAN}socketley remove *${NC}        # stop all + remove all"
    echo ""

    echo -e "${BOLD}send <name> [message]${NC}"
    echo "  Send message to server (broadcast) or client"
    echo -e "  ${CYAN}socketley send myserver \"Hello everyone\"${NC}"
    echo -e "  ${CYAN}echo \"Hello\" | socketley send myserver${NC}  # stdin"
    echo ""

    echo -e "${BOLD}restart <name> [flags]${NC}"
    echo "  Stop and start a runtime in one step. The runtime keeps the"
    echo "  configuration it already has: flags are handed to 'start', which"
    echo "  understands only -i, so they do NOT reconfigure anything."
    echo -e "  ${CYAN}socketley restart api${NC}"
    echo -e "  ${CYAN}socketley edit api -p 9001 && socketley restart api${NC}  # new port"
    echo ""

    echo -e "${BOLD}ls [--json|-j|--format json] [--silent|-s] [columns...]${NC}"
    echo "  List all runtimes (Docker-style: ID, NAME, TYPE, PORT, CONN, STATUS, CREATED, GROUP)"
    echo "  --json / --format json: Output as JSON array for scripting"
    echo "  --silent / -s: Print only runtime names (one per line)"
    echo "  Column selectors: --id --name --type --port --status --conn --owner --created --group"
    echo -e "  ${CYAN}socketley ls --name --port --status${NC}  # show only selected columns"
    echo ""

    echo -e "${BOLD}ps [-a|--all] [--json|-j|--format json] [--silent|-s] [columns...]${NC}"
    echo "  List running runtimes (same format as ls, includes uptime)"
    echo "  A runtime that did not come up is 'failed' and does NOT appear here --"
    echo "  if nothing is running you get no output at all. Use ps -a, or ls."
    echo "  -a / --all: List every state, with STATUS showing Created/Stopped/Failed"
    echo "  --json / --format json: Output as JSON array for scripting"
    echo "  --silent / -s: Print only runtime names (one per line)"
    echo "  Column selectors: --id --name --type --port --uptime --conn --owner --created"
    echo -e "  ${CYAN}socketley ps -a${NC}  # includes anything that failed to start"
    echo ""

    echo -e "${BOLD}stats <name|pattern>...${NC}"
    echo "  Show runtime statistics. Accepts multiple names, glob patterns"
    echo -e "  ${CYAN}socketley stats myserver${NC}"
    echo -e "  ${CYAN}socketley stats api* cache*${NC}  # stats for matching"
    echo -e "  ${CYAN}socketley stats *${NC}            # stats for all"
    echo ""

    echo -e "${BOLD}reload <name|pattern>...${NC}"
    echo "  Restart running runtimes (stop + start). Glob patterns supported"
    echo "  A runtime in a worker process has its child taken down and forked"
    echo "    again, so an edited script takes effect.  Waited for and answered"
    echo "    for like start: exit 1 if the worker refuses it or on_start raises."
    echo -e "  ${CYAN}socketley reload myserver${NC}"
    echo -e "  ${CYAN}socketley reload api*${NC}  # restart all api- runtimes"
    echo -e "  ${CYAN}socketley reload *${NC}     # restart all running"
    echo ""

    echo -e "${BOLD}reload-lua <name|pattern>...${NC}"
    echo "  Hot-reload Lua script without stopping the runtime"
    echo "  on_start runs again on the new script — subscriptions and timers live"
    echo "    in the context that was just destroyed, so anything on_start does"
    echo "    must be safe to do twice.  on_stop does NOT run: nothing stopped."
    echo "  Exit 1 when the script would not load, or when its on_start raised."
    echo -e "  ${CYAN}socketley reload-lua myserver${NC}"
    echo -e "  ${CYAN}socketley reload-lua *${NC}"
    echo ""

    echo -e "${BOLD}show <name|pattern>...${NC}"
    echo "  Print runtime JSON configuration. Glob patterns supported"
    echo -e "  ${CYAN}socketley show myserver${NC}"
    echo -e "  ${CYAN}socketley show cache*${NC}   # all cache runtimes"
    echo -e "  ${CYAN}socketley show *${NC}        # all runtimes"
    echo ""

    echo -e "${BOLD}edit <name> [flags]${NC}"
    echo "  Edit runtime configuration"
    echo -e "  ${CYAN}socketley edit myserver${NC}           # Opens config in \$EDITOR"
    echo -e "  ${CYAN}socketley edit myserver -r${NC}        # Opens editor, auto-reloads Lua"
    echo -e "  ${CYAN}socketley edit myserver -p 9001${NC}   # Direct flag-based edit"
    echo "  Flag-based edit takes a SUBSET of the create flags: the common ones"
    echo "  (-p -b -bp -bt -bpt --log -w --max-connections --rate-limit"
    echo "  --global-rate-limit --idle-timeout -g), the server/client flags, and"
    echo "  the proxy mesh flags (--strategy --health-* --circuit-* "
    echo "  --backend-timeout --retry --retry-all). Everything else - including"
    echo "  --lua, --drain, --reconnect, proxy --backend/--protocol/--sidecar and"
    echo "  every cache flag - is rejected with 'unknown flag'. Use the editor or"
    echo "  'import' for those."
    echo "  The TLS flags are the exception: on every runtime type --tls --cert"
    echo "  --key --ca - and on a proxy --client-ca/--client-cert/--client-key -"
    echo "  are accepted here and take effect at its next start; an edit that would"
    echo "  leave a set incomplete is refused and changes nothing. So is --tls on a"
    echo "  CACHE that replicates: replication is not encrypted."
    echo "  --cpus and --sqpoll/--no-sqpoll are refused too, and not as policy:"
    echo "  io_uring fixes a ring's CPU set and polling mode when the ring is"
    echo "  created and offers nothing to change them with. Recreate the runtime."
    echo ""

    echo -e "${BOLD}import <name> <json>${NC}"
    echo "  Update a runtime's configuration from a JSON string"
    echo "  With no <json> argument the document is read from stdin, so 'show'"
    echo "  pipes straight into 'import' with no command-line length limit."
    echo "  Same fields as the interactive editor. Read-only fields are ignored."
    echo "  Port/protocol/UDP cannot be changed while running."
    echo "  tls/cert_path/key_path/ca_path are honoured on every runtime type;"
    echo "  client_ca/client_cert/client_key belong to a proxy alone. An incomplete"
    echo "  set is rejected, as is tls beside replicate_target on a CACHE. Omitting"
    echo "  fields clears them, which is how a runtime restored from an old state"
    echo "  file is made startable again."
    echo -e "  ${CYAN}socketley import myserver '{\"port\":9001,\"rate_limit\":500}'${NC}"
    echo -e "  ${CYAN}socketley show myserver | socketley import myserver${NC}"
    echo ""

    echo -e "${BOLD}owner <name>${NC}"
    echo "  Show ownership info: parent, children, on_parent_stop policy"
    echo -e "  ${CYAN}socketley owner chess-rapid${NC}"
    echo ""

    echo -e "${BOLD}version | --version | -v${NC}"
    echo "  Print version number and exit"
    echo -e "  ${CYAN}socketley --version${NC}"
    echo ""

    echo -e "${BOLD}--lua <file.lua>${NC}"
    echo "  Load Lua configuration"
    echo -e "  ${CYAN}socketley --lua setup.lua${NC}"
    echo ""

    echo -e "${BOLD}cluster [subcommand]${NC}"
    echo "  Multi-daemon cluster inspection (requires daemon in cluster mode;"
    echo "  says 'cluster mode is off' with the reason when it is not)"
    echo -e "  ${CYAN}socketley cluster ls${NC}        # list daemons"
    echo -e "  ${CYAN}socketley cluster ps${NC}        # list all runtimes"
    echo -e "  ${CYAN}socketley cluster group api${NC}  # group members"
    echo -e "  ${CYAN}socketley cluster stats${NC}     # cluster summary"
    echo -e "  ${CYAN}socketley cluster watch${NC}     # live refresh"
    echo ""

    echo -e "${BOLD}dashboard${NC}"
    echo "  Show the live dashboard URL. Requires metrics_port in config.lua."
    echo "  Dashboard served at the metrics endpoint root (/)."
    echo -e "  ${CYAN}socketley dashboard${NC}"
    echo ""
    echo "  JSON API endpoints:"
    echo -e "  ${CYAN}/api/overview${NC}          # cluster/daemon summary"
    echo -e "  ${CYAN}/api/runtimes${NC}          # all runtimes"
    echo -e "  ${CYAN}/api/runtime/<name>${NC}    # single runtime details"
    echo ""

    read -p "Press Enter to continue..."
    main_menu
}

