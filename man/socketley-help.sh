    echo "    How long one Lua callback invocation may hold the event-loop thread"
    echo "    before it is stopped with an error. 0 switches the bound off and"
    echo "    installs no instruction hook, which is also what restores LuaJIT's"
    echo "    JIT. This is the default for scripts that declare no"
    echo "    callback_timeout_ms of their own; a script that does wins. Inherited"
    echo "    by worker processes. See 'socketley help lua'."
    echo ""
    echo -e "  ${CYAN}SOCKETLEY_CACHE_TTL_SWEEP_MS${NC}  default 500"
    echo "    Interval between sweeps for expired cache keys. Never affects"
    echo "    correctness — expired keys are never served regardless, since every"
    echo "    read checks the expiry itself. It only controls how fast untouched"
    echo "    keys release memory. Keep it above SOCKETLEY_SQPOLL_IDLE_MS."
    echo ""
    echo -e "  ${CYAN}SOCKETLEY_CACHE_BUF_SIZE${NC}      default 4096"
